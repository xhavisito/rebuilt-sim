const dicts: Record<Lang, Record<TKey, string>> = { es, en };
let lang: Lang = 'es';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l === 'es' ? 'es-MX' : 'en';
}

export function getLang(): Lang {
  return lang;
}

export function t(key: TKey, params?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? es[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

/** Texto bilingüe directo (para mensajes de reglas/validación). */
export function tx(m: { es: string; en: string }): string {
  return m[lang];
}
